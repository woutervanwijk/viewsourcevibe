// The single list of services, trackers and technologies the app can detect.
// Every tab (Privacy, Services, Metadata, Sovereignty) and the logos read
// from this catalogue, so a service has one name and one set of signals.

enum DetectionCategory {
  // Tracking (shown in Privacy; weight orders them by intrusiveness).
  advertising('Advertising', tracking: 5),
  behavior('Session Recording', tracking: 4),
  social('Social & Widgets', tracking: 3),
  analytics('Analytics', tracking: 2),
  marketing('Marketing & CRM', tracking: 1),
  // Other third-party services.
  consent('Privacy & Consent'),
  fonts('Fonts & Icons'),
  ecommerce('E-commerce & Payments'),
  cloud('Cloud & Infrastructure'),
  // Technologies (shown in Metadata).
  cms('CMS', tech: true),
  staticSite('Static Site', tech: true),
  framework('Framework', tech: true),
  library('Library', tech: true),
  cssFramework('CSS Framework', tech: true),
  plugin('Plugins', tech: true),
  webServer('Web Server', tech: true),
  backend('Backend', tech: true),
  cdn('CDN', tech: true),
  platform('Platform', tech: true),
  storage('Storage', tech: true),
  cache('Cache', tech: true);

  final String label;

  /// > 0 for trackers; higher is more intrusive.
  final int tracking;
  final bool tech;
  const DetectionCategory(this.label, {this.tracking = 0, this.tech = false});

  bool get isTracking => tracking > 0;
}

/// Marker for open-source software that runs wherever it is hosted.
const selfHosted = 'self-hosted';

class Entity {
  final String name;
  final DetectionCategory category;

  /// Hosts (and their subdomains) that belong to this service.
  final List<String> hosts;

  /// Regexes matched against page code and request URLs. A first capture
  /// group, if any, is the version.
  final List<String> patterns;

  /// First-party cookie names this service sets; a trailing `*` is a prefix.
  final List<String> cookies;

  /// Response header name (lowercase) → regex on its value ('' = present).
  final Map<String, String> headers;

  /// Regex on the generator meta tag; a capture group is the version.
  final String? generator;

  /// Vendor HQ country (ISO code) or [selfHosted].
  final String? origin;

  /// Domain whose favicon is the logo; defaults to the first host.
  final String? logo;

  /// Other names (old labels, cookie providers) that refer to this entity.
  final List<String> aliases;

  /// Only detected when this entity is detected too (plugins).
  final String? parent;

  /// URL regexes of requests that report the visit itself (pageview pings),
  /// for services that are not trackers but still log who visits.
  final List<String> beacons;

  const Entity(
    this.name,
    this.category, {
    this.hosts = const [],
    this.patterns = const [],
    this.cookies = const [],
    this.headers = const {},
    this.generator,
    this.origin,
    this.logo,
    this.aliases = const [],
    this.parent,
    this.beacons = const [],
  });

  String? get logoDomain => logo ?? hosts.firstOrNull;
}

