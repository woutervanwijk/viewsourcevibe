final Map<String, Entity> _byName = {
  for (final e in catalog) ...{
    e.name.toLowerCase(): e,
    for (final a in e.aliases) a.toLowerCase(): e,
  }
};

final Map<String, Entity> _byHost = {
  for (final e in catalog)
    for (final h in e.hosts) h: e,
};

/// Entity by name or alias (case-insensitive).
Entity? entityNamed(String name) => _byName[name.toLowerCase().trim()];

/// Entity owning [host], preferring the most specific (longest) host.
Entity? entityForHost(String host) {
  var h = host.toLowerCase();
  while (h.contains('.')) {
    final e = _byHost[h];
    if (e != null) return e;
    h = h.substring(h.indexOf('.') + 1);
  }
  return null;
}

/// Vendor HQ country (or [selfHosted]) for a detected name.
String? vendorOriginFor(String name) => entityNamed(name)?.origin;

/// Domain whose logo represents [label]: an entity name/alias, or a label
/// that contains one (e.g. "Bootstrap 5.3"); null when unknown.
String? logoDomainFor(String label) {
  final exact = entityNamed(label);
  if (exact != null) return exact.logoDomain;
  final l = label.toLowerCase();
  String? best;
  for (final key in _byName.keys) {
    if (key.length > 3 && l.contains(key) && key.length > (best?.length ?? 0)) {
      best = key;
    }
  }
  return best == null ? null : _byName[best]!.logoDomain;
}
