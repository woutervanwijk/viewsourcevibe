// Generates lib/utils/public_suffix.g.dart from the vendored Public Suffix
// List (tool/data/public_suffix_list.dat, pinned in tool/data/PSL_VERSION).
//
//   dart run tool/gen_public_suffix.dart
//
// Plain Dart (no Flutter imports); the unit test calls [generatePublicSuffix]
// to check that the committed file is not stale.
import 'dart:io';

String _q(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

/// Value of `KEY:` in the PSL_VERSION file, or 'unknown'.
String _versionField(String versionFile, String key) {
  for (final line in versionFile.split('\n')) {
    if (line.toLowerCase().startsWith('${key.toLowerCase()}:')) {
      return line.substring(key.length + 1).trim();
    }
  }
  return 'unknown';
}

/// Builds the Dart source for [dat]. ICANN and PRIVATE sections are both
/// included. Deterministic: every set is sorted.
String generatePublicSuffix(String dat, String versionFile) {
  final rules = <String>{};
  final wildcards = <String>{};
  final exceptions = <String>{};
  for (final raw in dat.split('\n')) {
    final line = raw.trim();
    if (line.isEmpty || line.startsWith('//')) continue;
    final rule = line.split(RegExp(r'\s')).first.toLowerCase();
    if (rule.startsWith('!')) {
      exceptions.add(rule.substring(1));
    } else if (rule.startsWith('*.')) {
      wildcards.add(rule.substring(2));
    } else {
      rules.add(rule);
    }
  }

  void emit(StringBuffer b, String name, String doc, Set<String> set) {
    b
      ..writeln()
      ..writeln('/// $doc')
      ..writeln('const Set<String> $name = {');
    for (final r in (set.toList()..sort())) {
      final line = '  ${_q(r)},';
      b.writeln(line);
    }
    b.writeln('};');
  }

  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_public_suffix.dart - do not edit.')
    ..writeln('// Regenerate with: dart run tool/gen_public_suffix.dart')
    ..writeln('//')
    ..writeln('// Data: Public Suffix List, https://publicsuffix.org/list/')
    ..writeln('// Version ${_versionField(versionFile, 'VERSION')}, '
        'commit ${_versionField(versionFile, 'COMMIT')}, '
        'license ${_versionField(versionFile, 'license')}.')
    ..writeln('// Modified: converted to Dart sets (ICANN and PRIVATE sections).')
    ..writeln("// See the licence in the repository's THIRD_PARTY_NOTICES.md.");
  emit(b, 'publicSuffixRules', 'Plain rules, e.g. `co.uk`.', rules);
  emit(b, 'publicSuffixWildcards',
      'The part after `*.` of wildcard rules, e.g. `kawasaki.jp`.', wildcards);
  emit(b, 'publicSuffixExceptions',
      'The part after `!` of exception rules, e.g. `city.kawasaki.jp`.',
      exceptions);
  return b.toString();
}

void main() {
  final dat = File('tool/data/public_suffix_list.dat').readAsStringSync();
  final version = File('tool/data/PSL_VERSION').readAsStringSync();
  File('lib/utils/public_suffix.g.dart')
      .writeAsStringSync(generatePublicSuffix(dat, version));
  stdout.writeln('Public Suffix List written to lib/utils/public_suffix.g.dart');
}
